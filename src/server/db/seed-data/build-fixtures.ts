function splitCsvLine(line: string): string[] {
  const out: string[] = [];
  let cur = "";
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === '"' && line[i + 1] === '"') {
        cur += '"';
        i++;
      } else if (c === '"') q = false;
      else cur += c;
    } else if (c === '"') q = true;
    else if (c === ",") {
      out.push(cur);
      cur = "";
    } else cur += c;
  }
  out.push(cur);
  return out;
}
function csv(name: string): Record<string, string>[] {
  const lines = readFileSync(join(DIR, name), "utf8").trim().split("\n");
  const h = splitCsvLine(lines[0]);
  return lines.slice(1).map((l) => {
    const c = splitCsvLine(l);
    return Object.fromEntries(h.map((k, i) => [k, c[i] ?? ""]));
  });
}
