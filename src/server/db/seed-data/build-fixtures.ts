// --- Data migration SQL (idempotent) ---
const lit = (v: unknown) =>
  v === null || v === undefined
    ? "NULL"
    : typeof v === "number" || typeof v === "boolean"
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;
const snake = (k: string) => k.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`);
function insert(table: string, rows: Record<string, unknown>[], pk: string) {
  const cols = Object.keys(rows[0]);
  const values = rows
    .map((r) => `(${cols.map((c) => lit(r[c])).join(", ")})`)
    .join(",\n  ");
  return `INSERT INTO "${table}" (${cols.map((c) => `"${snake(c)}"`).join(", ")})\nVALUES\n  ${values}\nON CONFLICT ("${pk}") DO NOTHING;`;
}
